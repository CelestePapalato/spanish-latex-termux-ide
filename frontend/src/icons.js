// Replaces <i data-i="name" data-s="16"></i> with the matching SVG.
export function hydrate(root = document) {
  root.querySelectorAll('[data-i]').forEach(el => {
    el.innerHTML = icon(el.dataset.i, +el.dataset.s || 18);
    el.classList.add('ico');
    el.removeAttribute('data-i');
  });
}

// Icon per file type (for the file tree and the tabs).
export function fileIcon(name) {
  const e = (name.split('.').pop() || '').toLowerCase();
  if (e === 'tex' || e === 'latex' || e === 'ltx') return ['file-text', '#ED254E'];
  if (e === 'bib' || e === 'bst') return ['book', '#d97706'];
  if (e === 'sty' || e === 'cls' || e === 'def' || e === 'cfg') return ['code', '#7c6cf0'];
  if (/^(png|jpe?g|gif|svg|webp|eps)$/.test(e)) return ['image', '#2f8fe0'];
  if (e === 'pdf') return ['file', '#ED254E'];
  return ['file', '#7f9aa1'];
}
